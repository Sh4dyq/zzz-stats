-- АВТОЗАПОЛНЕНИЕ РОСТЕРОВ: ростер игрока может собираться автоматически из пиков
-- в матчах турнира. Чтобы авто-сбор не перетирал ручные правки — флаг source.
-- source : кто последним сформировал ростер игрока в этом турнире.
--   'auto'   — собран автоматически из match_picks при сохранении результата.
--              Авто-сбор СВОБОДНО пересобирает такие строки.
--   'manual' — ростер правился вручную в админке (Игроки → Ростер).
--              Авто-сбор такие ростеры НЕ ТРОГАЕТ (защита от перетира).
-- Дефолт 'manual' — всё, что уже есть в БД, считаем ручным и защищаем.
alter table player_rosters add column if not exists source text not null default 'manual';

-- На случай существующих строк без значения.
update player_rosters set source = coalesce(source,'manual') where source is null;
